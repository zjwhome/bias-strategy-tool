STOP_PCT = 0.97          # 硬止损：跌破买入日最低价 -3%
COST_PCT = 0.4           # 单笔往返交易成本（佣金+印花税+滑点）
HOLD_DAYS = 6


def simulate(sig):
    entry = sig["entry"]
    ma_target = sig["close_eval"] / (1 + sig["bias"] / 100.0)   # 反推 24 日均线目标位
    stop_price = entry * STOP_PCT

    for i, (low, close) in enumerate(sig["days"][:HOLD_DAYS]):
        if low <= stop_price:
            return -3.0, i + 1, "止损"
        if close >= ma_target:
            return (close / entry - 1) * 100, i + 1, "回归均线"

    close = sig["days"][HOLD_DAYS - 1][1]
    return (close / entry - 1) * 100, HOLD_DAYS, "到期"


def stats(rows):
    if not rows:
        return None
    rets = [r["ret"] for r in rows]
    wins = [r for r in rows if r["ret"] > 0]
    gp = sum(r["ret"] for r in rows if r["ret"] > 0)
    gl = abs(sum(r["ret"] for r in rows if r["ret"] <= 0))
    return dict(
        n=len(rows),
        win=len(wins) / len(rows) * 100,
        avg=st.mean(rets),
        med=st.median(rets),
        best=max(rets),
        worst=min(rets),
        pf=(gp / gl) if gl > 0 else float("inf"),
        net=st.mean(rets) - COST_PCT,
    )


def show(title, rows):
    s = stats(rows)
    if not s:
        print(f"{title:<22} 无样本")
        return
    print(f"{title:<22} n={s['n']:<3} 胜率={s['win']:>5.1f}%  均收益={s['avg']:>+6.2f}%  "
          f"中位={s['med']:>+6.2f}%  盈亏比={s['pf']:>4.2f}  扣费后={s['net']:>+6.2f}%")


